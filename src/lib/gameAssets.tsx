const KEYWORD_EMOJI: [string, string][] = [
  ["cream", "🍦"],
  ["dot", "⚫"],
  ["block", "🧱"],
];

export function getThemeVisual(theme: string): string {
  return THEME_EMOJI[theme.trim().toLowerCase()] || "⭐";
}

export function emojiFor(label: string): string | undefined {
  const key = label.trim().toLowerCase().replace(/\s+/g, " ");
  const direct = LABEL_EMOJI[key];
  if (direct) return direct;
  for (const [needle, emoji] of KEYWORD_EMOJI) {
    if (key.includes(needle)) return emoji;
  }
  return undefined;
}

const FALLBACK_PALETTE = [
  "bg-rose-200 text-rose-700 border-rose-300",
  "bg-sky-200 text-sky-700 border-sky-300",
  "bg-amber-200 text-amber-700 border-amber-300",
  "bg-emerald-200 text-emerald-700 border-emerald-300",
  "bg-violet-200 text-violet-700 border-violet-300",
  "bg-orange-200 text-orange-700 border-orange-300",
];

export function letterMedalClass(label: string): string {
  let hash = 0;
  for (let index = 0; index < label.length; index += 1) {
    hash = (hash * 31 + label.charCodeAt(index)) >>> 0;
  }
  return FALLBACK_PALETTE[hash % FALLBACK_PALETTE.length];
}

export function LetterMedal({ label, className = "" }: { label: string; className?: string }) {
  const initial = label.trim().charAt(0).toUpperCase() || "?";
  return (
    <span
      aria-hidden="true"
      className={`grid place-items-center rounded-2xl border-2 font-black ${letterMedalClass(label)} ${className}`}
    >
      {initial}
    </span>
  );
}
